class Fund(Base):
    __tablename__ = "funds"

    id: Mapped[uuid.UUID] = _uuid_pk()
    name: Mapped[str] = mapped_column(String(255), nullable=False)
    manager: Mapped[str] = mapped_column(String(255), nullable=False)
    strategy: Mapped[str] = mapped_column(String(255), nullable=False)
    offering: Mapped[Offering] = mapped_column(_pg_enum(Offering, "offering"), nullable=False)
    min_check: Mapped[Decimal] = mapped_column(Money, nullable=False)
    closing: Mapped[date | None] = mapped_column(Date)
    created_at: Mapped[datetime] = _created_at()

    attempts: Mapped[list["VerificationAttempt"]] = relationship(back_populates="fund")

    __table_args__ = (CheckConstraint("min_check >= 0", name="min_check_non_negative"),)


class Investor(Base):
    """A reusable investor passport. Not tied to any single fund."""

    __tablename__ = "investors"

    id: Mapped[uuid.UUID] = _uuid_pk()
    legal_name: Mapped[str] = mapped_column(String(255), nullable=False)
    email: Mapped[str] = mapped_column(String(320), nullable=False, unique=True)
    country: Mapped[str] = mapped_column(String(2), nullable=False)  # ISO 3166-1 alpha-2
    investor_type: Mapped[InvestorType] = mapped_column(
        _pg_enum(InvestorType, "investor_type"), nullable=False
    )
    entity_name: Mapped[str | None] = mapped_column(String(255))
    entity_kind: Mapped[EntityKind | None] = mapped_column(_pg_enum(EntityKind, "entity_kind"))
    created_at: Mapped[datetime] = _created_at()

    attempts: Mapped[list["VerificationAttempt"]] = relationship(back_populates="investor")
    audit_logs: Mapped[list["AuditLog"]] = relationship(back_populates="investor")

    __table_args__ = (
        CheckConstraint(
            "(investor_type = 'entity') = (entity_name IS NOT NULL AND entity_kind IS NOT NULL)",
            name="entity_fields_match_type",
        ),
    )


class VerificationAttempt(Base):
    """One Roundtable payload checked against the rules engine.

    fund_id is nullable: set when a fund requested the check, NULL when the LP
    verified on their own (passport flow).
    """

    __tablename__ = "verification_attempts"

    id: Mapped[uuid.UUID] = _uuid_pk()
    investor_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("investors.id", ondelete="RESTRICT"), nullable=False
    )
    fund_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("funds.id", ondelete="RESTRICT"), nullable=True
    )
    pathway: Mapped[Pathway] = mapped_column(_pg_enum(Pathway, "pathway"), nullable=False)
    status: Mapped[AttemptStatus] = mapped_column(
        _pg_enum(AttemptStatus, "attempt_status"),
        nullable=False,
        server_default=AttemptStatus.RECEIVED.value,
    )
    decision: Mapped[Decision | None] = mapped_column(_pg_enum(Decision, "decision"))

    # Roundtable figures plus the result of each exact_quote substring check.
    extracted_figures: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False)

    # Encrypted at rest; deferred so listing attempts never loads (or decrypts) it.
    raw_document_text: Mapped[str] = deferred(mapped_column(EncryptedText, nullable=False))
    # SHA-256 of the plain text: proves which document was checked without decrypting.
    raw_document_sha256: Mapped[str] = mapped_column(String(64), nullable=False)

    rejection_reason: Mapped[str | None] = mapped_column(Text)
    reviewed_by: Mapped[str | None] = mapped_column(String(255))
    reviewed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    created_at: Mapped[datetime] = _created_at()

    investor: Mapped[Investor] = relationship(back_populates="attempts")
    fund: Mapped[Fund | None] = relationship(back_populates="attempts")
    audit_logs: Mapped[list["AuditLog"]] = relationship(back_populates="attempt")

    __table_args__ = (
        Index("ix_verification_attempts_investor_created", "investor_id", "created_at"),
        CheckConstraint("raw_document_sha256 ~ '^[0-9a-f]{64}$'", name="sha256_hex"),
        CheckConstraint(
            "(status = 'rejected_quote_mismatch') = (rejection_reason IS NOT NULL)",
            name="rejection_reason_iff_rejected",
        ),
        CheckConstraint("(reviewed_by IS NULL) = (reviewed_at IS NULL)", name="review_pair"),
    )


class AuditLog(Base):
    """Append-only, hash-chained audit trail.

    entry_hash = SHA-256(prev_hash + canonical JSON of this entry), so editing or
    deleting any row breaks the chain. Postgres triggers (below) reject UPDATE,
    DELETE and TRUNCATE outright. Use append_audit_log() to write rows.
    """

    __tablename__ = "audit_logs"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    verification_attempt_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("verification_attempts.id", ondelete="RESTRICT")
    )
    investor_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("investors.id", ondelete="RESTRICT")
    )
    event_type: Mapped[str] = mapped_column(String(64), nullable=False)
    actor: Mapped[str] = mapped_column(String(255), nullable=False)
    payload: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False)
    prev_hash: Mapped[str | None] = mapped_column(String(64))
    entry_hash: Mapped[str] = mapped_column(String(64), nullable=False, unique=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )

    attempt: Mapped[VerificationAttempt | None] = relationship(back_populates="audit_logs")
    investor: Mapped[Investor | None] = relationship(back_populates="audit_logs")

    __table_args__ = (
        Index("ix_audit_logs_attempt_created", "verification_attempt_id", "created_at"),
    )


# --------------------------------------------------------------------------- #
# Audit log: hash-chained append + immutability
# --------------------------------------------------------------------------- #

# Arbitrary constant for pg_advisory_xact_lock: serialises chain appends so two
# concurrent writers can't both link to the same prev_hash.
_AUDIT_CHAIN_LOCK_ID = 506_000_001


def _canonical(data: dict[str, Any]) -> str:
    return json.dumps(data, sort_keys=True, separators=(",", ":"), default=str)


def compute_entry_hash(prev_hash: str | None, fields: dict[str, Any]) -> str:
    return hashlib.sha256(((prev_hash or "") + _canonical(fields)).encode("utf-8")).hexdigest()


def append_audit_log(
    db,
    *,
    event_type: str,
    actor: str,
    payload: dict[str, Any],
    verification_attempt_id: uuid.UUID | None = None,
    investor_id: uuid.UUID | None = None,
) -> AuditLog:
    """Add a hash-chained AuditLog row to `db` (normally a database.audit_session()).

    The caller's session commits it. The advisory lock is held until that commit.
    """
    db.execute(text("SELECT pg_advisory_xact_lock(:k)"), {"k": _AUDIT_CHAIN_LOCK_ID})
    prev_hash = db.execute(
        text("SELECT entry_hash FROM audit_logs ORDER BY id DESC LIMIT 1")
    ).scalar_one_or_none()

    created_at = datetime.now(timezone.utc)
    fields = {
        "verification_attempt_id": str(verification_attempt_id) if verification_attempt_id else None,
        "investor_id": str(investor_id) if investor_id else None,
        "event_type": event_type,
        "actor": actor,
        "payload": payload,
        "created_at": created_at.isoformat(),
    }
    entry = AuditLog(
        verification_attempt_id=verification_attempt_id,
        investor_id=investor_id,
        event_type=event_type,
        actor=actor,
        payload=payload,
        prev_hash=prev_hash,
        entry_hash=compute_entry_hash(prev_hash, fields),
        created_at=created_at,
    )
    db.add(entry)
    db.flush()
    return entry


class AuditLogImmutableError(Exception):
    pass


# Layer 1: the ORM refuses to update or delete audit rows.
@event.listens_for(AuditLog, "before_update")
def _block_audit_update(mapper, connection, target):
    raise AuditLogImmutableError("audit_logs is append-only: UPDATE is not allowed")


@event.listens_for(AuditLog, "before_delete")
def _block_audit_delete(mapper, connection, target):
    raise AuditLogImmutableError("audit_logs is append-only: DELETE is not allowed")


# Layer 2: Postgres refuses too, so raw SQL can't bypass the ORM.
# DDL() applies Python %-formatting, so the literal percent sign Postgres needs
# in RAISE is written doubled below.
_AUDIT_TRIGGER_DDL = """
CREATE OR REPLACE FUNCTION audit_logs_block_mutation() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'audit_logs is append-only: %% is not allowed', TG_OP
        USING ERRCODE = 'insufficient_privilege';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER audit_logs_no_update_delete
    BEFORE UPDATE OR DELETE ON audit_logs
    FOR EACH ROW EXECUTE FUNCTION audit_logs_block_mutation();

CREATE TRIGGER audit_logs_no_truncate
    BEFORE TRUNCATE ON audit_logs
    FOR EACH STATEMENT EXECUTE FUNCTION audit_logs_block_mutation();
"""

event.listen(AuditLog.__table__, "after_create", DDL(_AUDIT_TRIGGER_DDL))
