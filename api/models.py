"""SQLAlchemy models: Fund, Investor, VerificationAttempt, AuditLog.

Rules applied to every table:
- Primary keys are UUIDs generated by Postgres (except AuditLog, which uses an
  identity column so the hash chain has a strict order).
- Money columns are Numeric(15, 2), never float.
- Every foreign key is ON DELETE RESTRICT and no relationship cascades deletes,
  so deleting a parent can never remove audit history.
"""

