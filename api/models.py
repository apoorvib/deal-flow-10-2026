import hashlib
import json
import os
import uuid
from datetime import date, datetime, timezone
from decimal import Decimal
from typing import Any

from cryptography.fernet import Fernet, MultiFernet
from sqlalchemy import (
    DDL,
    BigInteger,
    CheckConstraint,
    Date,
    DateTime,
    Enum,
    ForeignKey,
    Index,
    Numeric,
    String,
    Text,
    event,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, deferred, mapped_column, relationship
from sqlalchemy.types import TypeDecorator

from database import Base

Money = Numeric(15, 2)


# --------------------------------------------------------------------------- #
# Column-level encryption
# --------------------------------------------------------------------------- #

def _load_fernet() -> MultiFernet:
    raw = os.environ.get("SAVY_FIELD_ENCRYPTION_KEY", "")
    keys = [k.strip() for k in raw.split(",") if k.strip()]
    if not keys:
        raise RuntimeError("SAVY_FIELD_ENCRYPTION_KEY is not set")
    # Newest key first: it encrypts new writes; every key is tried on read.
    return MultiFernet([Fernet(k.encode()) for k in keys])


_fernet = _load_fernet()


class EncryptedText(TypeDecorator):
    """Text encrypted with Fernet (AES-128-CBC + HMAC-SHA256) before it reaches Postgres.

    The database only ever stores the ciphertext token. Decryption fails loudly
    (InvalidToken) if the ciphertext was tampered with or the key is wrong.
    """

    impl = Text
    cache_ok = True

    def process_bind_param(self, value: str | None, dialect: Any) -> str | None:
        if value is None:
            return None
        return _fernet.encrypt(value.encode("utf-8")).decode("ascii")

    def process_result_value(self, value: str | None, dialect: Any) -> str | None:
        if value is None:
            return None
        return _fernet.decrypt(value.encode("ascii")).decode("utf-8")


